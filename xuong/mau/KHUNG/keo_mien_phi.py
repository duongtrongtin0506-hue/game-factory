def make(slug):
    out = ROOT / "HANG" / f"{datetime.date.today():%Y%m%d}-{slug}"
    tmp = ROOT / "_tam" / slug
    path, info, title, tagline, tags = mau.build(slug, tmp)
    check = kiem_cong_thuc.check(path, [f"{s}!{c}" for s, c in info["checks"]])
    if check["error_count"]:
        print(slug, "LỖI CÔNG THỨC – không đóng gói", check["errors"][:3])
        return None
    anh.render(path, tmp, title, tagline)
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(tmp, out)
    docs(slug, out, title, tagline, tags, info, check)
    return {"slug": slug, "formulas": check["formulas"], "errors": 0}


def main():
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    have = {p.name.split("-", 1)[1] for p in (ROOT / "HANG").glob("*-*") if p.is_dir()}
    queue = [s for s in mau.CATALOG if s not in have]
    for s in (queue if "--all" in sys.argv else queue[:1]):
        r = make(s)
        if r:
            nk = ROOT / "NHAT-KY.md"
            nk.write_text(nk.read_text(encoding="utf-8").rstrip("\n") + f"\n| {datetime.date.today():%d/%m} | mẫu miễn phí: {s} | {r['formulas']} công thức, 0 lỗi |\n", encoding="utf-8")
        print(json.dumps(r, ensure_ascii=False))
    shutil.rmtree(ROOT / "_tam", ignore_errors=True)


if __name__ == "__main__":
    main()
